export interface Qwen3SynthesisParams {
  apiKey: string;
  region?: string;
  model: string;
  text: string;
  voice: string;
  languageType?: string;
  instructions?: string;
  optimizeInstructions?: boolean;
}

function buildRequestBody(params: Qwen3SynthesisParams) {
  const input: Record<string, unknown> = {
    text: params.text,
    voice: params.voice,
  };

  if (params.languageType && params.languageType !== 'Auto') {
    input.language_type = params.languageType;
  }

  // Instructions only apply to qwen3-tts-instruct-flash
  if (params.model.includes('instruct') && params.instructions) {
    input.instructions = params.instructions;
    if (params.optimizeInstructions) {
      input.optimize_instructions = true;
    }
  }

  return {
    model: params.model,
    input,
  };
}

function base64ToArrayBuffer(base64: string): ArrayBuffer {
  const binaryString = atob(base64);
  const bytes = new Uint8Array(binaryString.length);
  for (let i = 0; i < binaryString.length; i++) {
    bytes[i] = binaryString.charCodeAt(i);
  }
  return bytes.buffer as ArrayBuffer;
}

/** Detect audio format from first bytes */
function detectAudioFormat(data: Uint8Array): 'mp3' | 'pcm' {
  if (data.length < 3) return 'pcm';
  // MP3 frame sync: 0xFF followed by 0xE0+ (11 sync bits set)
  if (data[0] === 0xFF && (data[1] & 0xE0) === 0xE0) return 'mp3';
  // ID3 tag header (MP3 with metadata)
  if (data[0] === 0x49 && data[1] === 0x44 && data[2] === 0x33) return 'mp3';
  return 'pcm';
}

/** Wrap raw PCM samples in a WAV container for browser playback.
 *  DashScope Qwen3-TTS streaming returns 24kHz, 16-bit, mono PCM. */
function wrapPcmInWav(
  pcmData: Uint8Array,
  sampleRate = 24000,
  channels = 1,
  bitsPerSample = 16,
): Uint8Array {
  const dataLength = pcmData.byteLength;
  const headerLength = 44;
  const wav = new Uint8Array(headerLength + dataLength);
  const view = new DataView(wav.buffer);

  // RIFF header
  wav.set([0x52, 0x49, 0x46, 0x46], 0); // "RIFF"
  view.setUint32(4, headerLength + dataLength - 8, true);
  wav.set([0x57, 0x41, 0x56, 0x45], 8); // "WAVE"

  // fmt chunk
  wav.set([0x66, 0x6D, 0x74, 0x20], 12); // "fmt "
  view.setUint32(16, 16, true); // chunk size
  view.setUint16(20, 1, true);  // PCM format
  view.setUint16(22, channels, true);
  view.setUint32(24, sampleRate, true);
  view.setUint32(28, sampleRate * channels * (bitsPerSample / 8), true);
  view.setUint16(32, channels * (bitsPerSample / 8), true);
  view.setUint16(34, bitsPerSample, true);

  // data chunk
  wav.set([0x64, 0x61, 0x74, 0x61], 36); // "data"
  view.setUint32(40, dataLength, true);
  wav.set(pcmData, headerLength);

  return wav;
}

/** Non-streaming synthesis — server downloads audio from DashScope URL, returns raw bytes */
export async function qwen3Synthesize(params: Qwen3SynthesisParams): Promise<ArrayBuffer> {
  const response = await fetch('/api/qwen3/synthesize', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      apiKey: params.apiKey,
      region: params.region,
      body: buildRequestBody(params),
    }),
  });

  if (!response.ok) {
    let message = `Qwen3 API error (${response.status})`;
    try {
      const errJson = await response.json();
      const upstreamCode = errJson?.upstreamCode ? ` [${errJson.upstreamCode}]` : '';
      const upstreamMessage = errJson?.upstreamMessage;
      message = upstreamMessage
        ? `${errJson?.error || message}${upstreamCode}: ${upstreamMessage}`
        : (errJson?.error || message);
    } catch {
      const text = await response.text();
      if (text) message = `${message}: ${text}`;
    }
    throw new Error(message);
  }

  // Server returns raw audio bytes (Content-Type: audio/mpeg)
  const contentType = response.headers.get('content-type') || '';
  if (contentType.includes('audio/')) {
    return response.arrayBuffer();
  }

  // Fallback: if server returned JSON (e.g. unexpected format), throw with details
  const json = await response.json();
  throw new Error(`Unexpected response format: ${JSON.stringify(json).slice(0, 200)}`);
}

export interface StreamingResult {
  ttfbMs: number;
  totalMs: number;
  buffer: ArrayBuffer;
  mimeType: string;
}

/** Streaming synthesis — parses base64 SSE chunks, returns metrics + full buffer */
export async function qwen3SynthesizeStreaming(
  params: Qwen3SynthesisParams,
  audioElement: HTMLAudioElement,
): Promise<StreamingResult> {
  const startTime = performance.now();
  let ttfbMs = 0;

  const response = await fetch('/api/qwen3/synthesize-stream', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      apiKey: params.apiKey,
      region: params.region,
      body: buildRequestBody(params),
    }),
  });

  if (!response.ok) {
    let message = `Qwen3 streaming API error (${response.status})`;
    try {
      const errJson = await response.json();
      const upstreamCode = errJson?.upstreamCode ? ` [${errJson.upstreamCode}]` : '';
      const upstreamMessage = errJson?.upstreamMessage;
      message = upstreamMessage
        ? `${errJson?.error || message}${upstreamCode}: ${upstreamMessage}`
        : (errJson?.error || message);
    } catch {
      const text = await response.text();
      if (text) message = `${message}: ${text}`;
    }
    throw new Error(message);
  }

  if (!response.body) {
    throw new Error('No response body for streaming');
  }

  const reader = response.body.getReader();
  const decoder = new TextDecoder();
  const audioChunks: ArrayBuffer[] = [];
  let buffer = '';

  while (true) {
    const { done, value } = await reader.read();
    if (done) break;

    buffer += decoder.decode(value, { stream: true });

    const lines = buffer.split('\n');
    buffer = lines.pop() || '';

    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed === 'data: [DONE]') continue;

      const jsonStr = trimmed.startsWith('data:') ? trimmed.slice(5).trim() : trimmed;

      try {
        const chunk = JSON.parse(jsonStr);
        // Qwen3-TTS streaming returns base64-encoded audio in output.audio.data
        const audioData = chunk.output?.audio?.data;
        if (audioData) {
          const audioBuffer = base64ToArrayBuffer(audioData);
          if (ttfbMs === 0) {
            ttfbMs = Math.round(performance.now() - startTime);
          }
          audioChunks.push(audioBuffer);
        }
        // Check for errors
        if (chunk.code) {
          throw new Error(`Qwen3 streaming error [${chunk.code}]: ${chunk.message || 'Unknown error'}`);
        }
      } catch (e) {
        if (e instanceof SyntaxError) continue;
        throw e;
      }
    }
  }

  const totalMs = Math.round(performance.now() - startTime);

  // Concatenate all chunks
  const totalLength = audioChunks.reduce((sum, chunk) => sum + chunk.byteLength, 0);
  const fullBuffer = new Uint8Array(totalLength);
  let offset = 0;
  for (const chunk of audioChunks) {
    fullBuffer.set(new Uint8Array(chunk), offset);
    offset += chunk.byteLength;
  }

  // DashScope Qwen3-TTS streaming may return raw PCM (24kHz, 16-bit, mono)
  // or MP3 depending on the model. Detect format and wrap PCM in WAV if needed.
  const format = detectAudioFormat(fullBuffer);
  console.log(
    `[Qwen3] Streaming audio: ${audioChunks.length} chunks, ${totalLength} bytes, ` +
    `format=${format}, first bytes=[${Array.from(fullBuffer.slice(0, 8)).map(b => '0x' + b.toString(16).padStart(2, '0')).join(', ')}]`
  );

  let playBuffer: Uint8Array;
  let mimeType: string;
  if (format === 'pcm') {
    playBuffer = wrapPcmInWav(fullBuffer);
    mimeType = 'audio/wav';
  } else {
    playBuffer = fullBuffer;
    mimeType = 'audio/mpeg';
  }

  // Play the full audio
  const blob = new Blob([playBuffer.buffer as ArrayBuffer], { type: mimeType });
  const audioUrl = URL.createObjectURL(blob);
  audioElement.src = audioUrl;
  audioElement.play();

  return {
    ttfbMs: ttfbMs || totalMs,
    totalMs,
    buffer: playBuffer.buffer as ArrayBuffer,
    mimeType,
  };
}
